"""Write web/src/pow-exceptions.js: the few (base, n) where Python's base ** n is not
the correctly rounded value.

The web port computes base ** n exactly with BigInt and rounds once, which matches
Python except where the C library's pow() (used by CPython) is off by one unit in
the last place. This script finds those cases so the port can reproduce them.

Run with the Python whose numbers you want to match (the games were written on
macOS). Covers every n from 0 until the result overflows or underflows to zero.
"""

from __future__ import annotations

import json
import pathlib
import platform
import sys

BASES = (0.9, 1.5, 0.95, 1.6, 1.4)  # full game: 0.9, 1.5 (2 is exact); demo: 0.95, 1.6, 1.4
OUT = pathlib.Path(__file__).resolve().parent.parent / "web" / "src" / "pow-exceptions.js"


def exceptions_for(base: float) -> tuple[list[list], int]:
    num, den = base.as_integer_ratio()
    top, bottom = 1, 1
    found = []
    n = 0
    while True:
        try:
            got = base ** n
        except OverflowError:
            return found, n
        exact = top / bottom  # int / int is correctly rounded in CPython
        if got != exact:
            found.append([n, got.hex()])
        if got == 0.0:
            return found, n + 1
        top *= num
        bottom *= den
        n += 1


def main() -> int:
    table = {}
    limits = {}
    for base in BASES:
        found, limit = exceptions_for(base)
        table[repr(base)] = found
        limits[repr(base)] = limit
        print(f"{base}: {len(found)} exceptions in n < {limit}", file=sys.stderr)
    header = (
        "// Generated by tools/gen_pow_exceptions.py. Do not edit.\n"
        f"// Python {platform.python_version()} on {platform.system()} {platform.machine()}.\n"
        "// Maps base -> [[n, python_result_as_float_hex], ...] where Python's base ** n\n"
        "// differs from the correctly rounded value.\n"
    )
    body = "var POW_EXCEPTIONS = " + json.dumps(table, separators=(",", ":")) + ";\n"
    OUT.write_text(header + body + "if (typeof module !== \"undefined\") module.exports = POW_EXCEPTIONS;\n")
    print(f"wrote {OUT}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
